// Offline icon bundle for the React UI (src/renderer/nr). Adapted from the
// NoRisk Client launcher's scripts/generate-icon-bundle.mjs (GPL-3.0).
// Scans the sources for "prefix:name" literals and writes only those icons, so
// nothing is fetched from the Iconify API at runtime (CSP blocks it anyway).
import { createRequire } from 'node:module';
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIcons } from '@iconify/utils';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src', 'renderer', 'nr');
const outFile = join(srcDir, 'lib', 'icon-bundle.ts');
const attributionFile = join(root, 'THIRD_PARTY_ICONS.md');

const COLLECTIONS = ['solar', 'pixel'];
const NOT_ICONS = new Set(['hover', 'group-hover', 'focus', 'active', 'data', 'disabled', 'focus-visible', '0', 'visibility', 'overflow', 'http', 'https']);
const ICON_RE = /["'`]([a-z][a-z0-9-]*):([a-z0-9][a-z0-9-]*)["'`]/g;

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.tsx?$/.test(full)) out.push(full);
  }
  return out;
}

const found = new Map();
const unknown = new Map();
for (const file of walk(srcDir)) {
  if (file === outFile) continue;
  for (const [, prefix, name] of readFileSync(file, 'utf8').matchAll(ICON_RE)) {
    if (NOT_ICONS.has(prefix)) continue;
    if (!COLLECTIONS.includes(prefix)) {
      if (!unknown.has(prefix)) unknown.set(prefix, new Set());
      unknown.get(prefix).add(relative(root, file));
      continue;
    }
    if (!found.has(prefix)) found.set(prefix, new Set());
    found.get(prefix).add(name);
  }
}
if (unknown.size > 0) {
  console.error('Unknown icon prefixes. Add the set to COLLECTIONS, or the string to NOT_ICONS:');
  for (const [prefix, files] of unknown) console.error(`  ${prefix}:  ${[...files].slice(0, 3).join(', ')}`);
  process.exit(1);
}

const chunks = [];
const used = [];
let total = 0;
for (const prefix of COLLECTIONS) {
  const names = [...(found.get(prefix) ?? [])].sort();
  if (names.length === 0) continue;
  const collection = JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8'));
  const subset = getIcons(collection, names);
  const resolved = new Set([...Object.keys(subset?.icons ?? {}), ...Object.keys(subset?.aliases ?? {})]);
  const missing = names.filter((n) => !resolved.has(n));
  if (!subset || missing.length) {
    console.error(`Icons missing from @iconify-json/${prefix}:`);
    for (const n of missing) console.error(`  ${prefix}:${n}`);
    process.exit(1);
  }
  delete subset.lastModified;
  total += names.length;
  chunks.push(`addCollection(${JSON.stringify(subset)});`);
  used.push({ prefix, count: names.length, info: JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/info.json`), 'utf8')) });
}

const credits = used.map(({ prefix, count, info }) => `//   ${prefix} (${count}) — ${info.name} by ${info.author?.name ?? 'unknown'}, ${info.license?.title ?? 'unknown licence'}`).join('\n');
const banner = `// GENERATED by tools/gen-icons.mjs — do not edit.\n${credits}\nimport { addCollection } from '@iconify/react/offline';\n\n`;
const next = banner + chunks.join('\n') + '\n';
let prev = '';
try { prev = readFileSync(outFile, 'utf8'); } catch { /* first run */ }
if (prev !== next) writeFileSync(outFile, next);

writeFileSync(attributionFile, `# Third-party icon artwork

The launcher bundles ${total} icons from the sets below. The artwork is redistributed
unmodified; only the icons actually used are included, extracted from the \`@iconify-json/*\`
packages by \`tools/gen-icons.mjs\`.

GENERATED — the launcher build refreshes it.

${used.map(({ prefix, count, info }) => {
  const author = info.author?.url ? `[${info.author.name}](${info.author.url})` : (info.author?.name ?? 'unknown');
  const licence = info.license?.url ? `[${info.license.title}](${info.license.url})` : (info.license?.title ?? 'unknown');
  return `## ${info.name} (\`${prefix}\`)\n\n- ${count} icon${count === 1 ? '' : 's'} used of ${info.total ?? '?'}\n- Author: ${author}\n- Licence: ${licence}${info.license?.spdx ? ` (\`${info.license.spdx}\`)` : ''}`;
}).join('\n\n')}
`);
console.log(`icons: ${total} -> ${relative(root, outFile)}`);
